"""Generate the Go SDK from its pinned local Service contract.

Generation does not import, check out, or execute the Service.
"""

import json
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "codegen"
TARGET = ROOT / "generated"


def run(*args: str, cwd: Path = ROOT) -> None:
    subprocess.run(args, cwd=cwd, check=True)


def name_skill_sync(document: dict) -> None:
    """Name the shared inline union so oapi-codegen emits its JSON methods.

    Anonymous nullable unions otherwise become opaque structs without a JSON
    codec. This only factors identical schemas; the pinned input stays intact.
    """
    schemas = document["components"]["schemas"]
    if "AgentConfig-Input" not in schemas:
        return
    policy = schemas["AgentOverride-Input"]["properties"]["skill_sync"]["anyOf"][0]
    schemas["SkillSync"] = policy.copy()
    for name in ("AgentConfig-Input", "AgentConfig-Output"):
        config_policy = schemas[name]["properties"]["skill_sync"].copy()
        config_policy.pop("title", None)
        assert config_policy == policy
        schemas[name]["properties"]["skill_sync"] = {"$ref": "#/components/schemas/SkillSync"}
    for name in ("AgentOverride-Input", "AgentOverride-Output"):
        alternatives = schemas[name]["properties"]["skill_sync"]["anyOf"]
        assert alternatives[0] == policy
        alternatives[0] = {"$ref": "#/components/schemas/SkillSync"}


def guard_tool_search(output: Path, schemas: dict, package: str) -> None:
    """Keep the new strict discriminated union strict at both JSON boundaries."""
    if "ToolSearchConfig" not in schemas:
        return
    graph: dict = {}

    def collect(name: str) -> None:
        if name in graph:
            return
        graph[name] = schemas[name]

        def references(value: object) -> None:
            if isinstance(value, dict):
                reference = value.get("$ref")
                if isinstance(reference, str):
                    collect(reference.rsplit("/", 1)[1])
                for child in value.values():
                    references(child)
            elif isinstance(value, list):
                for child in value:
                    references(child)

        references(schemas[name])

    collect("ToolSearch")
    schema = {"$defs": graph}
    native = json.dumps(schema).replace("#/components/schemas/", "#/$defs/")
    template = (CONFIG / "union_validation.go.tmpl").read_text()
    (output.parent / "tool_search.gen.go").write_text(
        template.replace("{{PACKAGE}}", package).replace("{{SCHEMA}}", json.dumps(native))
    )
    text = output.read_text()
    marshal = "func (t ToolSearchConfig) MarshalJSON() ([]byte, error) {\n\tb, err := t.union.MarshalJSON()\n\treturn b, err\n}"
    unmarshal = (
        "func (t *ToolSearchConfig) UnmarshalJSON(b []byte) error {\n\terr := t.union.UnmarshalJSON(b)\n\treturn err\n}"
    )
    assert text.count(marshal) == text.count(unmarshal) == 1
    text = text.replace(
        marshal,
        'func (t ToolSearchConfig) MarshalJSON() ([]byte, error) {\n\tb, err := t.union.MarshalJSON()\n\tif err == nil { err = validateToolSearchJSON("ToolSearchConfig", b) }\n\treturn b, err\n}',
    )
    text = text.replace(
        unmarshal,
        'func (t *ToolSearchConfig) UnmarshalJSON(b []byte) error {\n\tif err := validateToolSearchJSON("ToolSearchConfig", b); err != nil { return err }\n\treturn t.union.UnmarshalJSON(b)\n}',
    )
    output.write_text(text)
    run("gofmt", "-w", str(output), str(output.parent / "tool_search.gen.go"))


def generate(document: dict, work: Path) -> Path:
    name_skill_sync(document)
    history = document["components"]["schemas"].get("MessageHistory")
    if history is not None:
        # Native provider adapters render nested objects in submitted key order.
        # RawMessage preserves that order and number tokens in both directions.
        history["items"]["x-go-type"] = "json.RawMessage"
    source = work / "openapi.json"
    source.write_text(json.dumps(document))
    output = work / "output"
    output.mkdir()
    run(
        "go",
        "run",
        "github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.0",
        "--config",
        str(CONFIG / "config.yaml"),
        "-o",
        str(output / "client.gen.go"),
        str(source),
    )
    guard_tool_search(output / "client.gen.go", document["components"]["schemas"], "generated")
    text = (output / "client.gen.go").read_text()
    secrets = "// Code generated by codegen/generate.py; DO NOT EDIT.\npackage generated\n\n"
    for name, schema in document["components"]["schemas"].items():
        if any(prop.get("writeOnly") for prop in schema.get("properties", {}).values()):
            assert f"type {name} struct" in text, f"Update the Go diagnostic adapter for {name}"
            secrets += f'func ({name}) String() string {{ return "{name} {{ .. }}" }}\n'
            secrets += f'func ({name}) GoString() string {{ return "{name} {{ .. }}" }}\n'
    (output / "secrets.gen.go").write_text(secrets)
    run("gofmt", "-w", str(output / "secrets.gen.go"))
    return output


def install(output: Path, target: Path) -> None:
    # Only generator-owned directories are replaced, including removed schemas.
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(output, target)


def generate_session(schema: dict, work: Path, output: Path) -> None:
    """Project the native schema graph into models-only OpenAPI generation.

    The graph has its own serialization names and continuation types, separate
    from HTTP's input/output schemas. No wire definitions are maintained here.
    """
    native_json = json.dumps(schema, separators=(",", ":"))
    # Native arbitrary JSON stays raw even inside nullable codecs and unions;
    # their generated UnmarshalJSON methods otherwise round numbers to float64.
    schema = json.loads(json.dumps(schema))
    schema["$defs"]["JsonValue"]["x-go-type"] = "json.RawMessage"
    schema["$defs"]["Delta"]["properties"]["event"]["x-go-type"] = "map[string]json.RawMessage"
    # Nullable inline unions need a named codec, as on HTTP AgentOverride.
    policy = schema["$defs"]["AgentOverride"]["properties"]["skill_sync"]["anyOf"]
    schema["$defs"]["SkillSync"] = policy[0].copy()
    policy[0] = {"$ref": "#/$defs/SkillSync"}
    document = {
        "openapi": "3.1.0",
        "info": {"title": schema["title"], "version": "1"},
        "paths": {},
        "components": {"schemas": schema["$defs"]},
    }
    source = work / "session.json"
    source.write_text(json.dumps(document).replace("#/$defs/", "#/components/schemas/"))
    output.mkdir()
    (output / "schema.gen.go").write_text(
        "// Code generated by codegen/generate.py; DO NOT EDIT.\npackage sessionstream\n\n"
        f"const JSONSchema = {json.dumps(native_json)}\n"
    )
    run("gofmt", "-w", str(output / "schema.gen.go"))
    run(
        "go",
        "run",
        "github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.0",
        "--config",
        str(CONFIG / "session.yaml"),
        "-o",
        str(output / "models.gen.go"),
        str(source),
    )
    guard_tool_search(output / "models.gen.go", schema["$defs"], "sessionstream")


def main() -> None:
    document = json.loads((ROOT / "contract/openapi.json").read_text())
    schema = json.loads((ROOT / "contract/session-stream.schema.json").read_text())
    with tempfile.TemporaryDirectory(prefix="a13n-codegen-") as temp:
        work = Path(temp)
        output = generate(document, work)
        generate_session(schema, work, output / "sessionstream")
        install(output, TARGET)


if __name__ == "__main__":
    main()
