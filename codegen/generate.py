"""Generate the Go SDK from its pinned local Service contract.

Generation does not import, check out, or execute the Service.
"""

import json
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "codegen"
TARGET = ROOT / "generated"


def run(*args: str, cwd: Path = ROOT) -> None:
    subprocess.run(args, cwd=cwd, check=True)


def name_skill_sync(document: dict) -> None:
    """Name the shared inline union so oapi-codegen emits its JSON methods.

    Anonymous nullable unions otherwise become opaque structs without a JSON
    codec. This only factors identical schemas; the pinned input stays intact.
    """
    schemas = document["components"]["schemas"]
    if "AgentConfig-Input" not in schemas:
        return
    policy = schemas["AgentOverride-Input"]["properties"]["skill_sync"]["anyOf"][0]
    schemas["SkillSync"] = policy.copy()
    for name in ("AgentConfig-Input", "AgentConfig-Output"):
        config_policy = schemas[name]["properties"]["skill_sync"].copy()
        config_policy.pop("title", None)
        assert config_policy == policy
        schemas[name]["properties"]["skill_sync"] = {"$ref": "#/components/schemas/SkillSync"}
    for name in ("AgentOverride-Input", "AgentOverride-Output"):
        alternatives = schemas[name]["properties"]["skill_sync"]["anyOf"]
        assert alternatives[0] == policy
        alternatives[0] = {"$ref": "#/components/schemas/SkillSync"}


def generate(document: dict, work: Path) -> Path:
    name_skill_sync(document)
    history = document["components"]["schemas"].get("MessageHistory")
    if history is not None:
        # Native provider adapters render nested objects in submitted key order.
        # RawMessage preserves that order and number tokens in both directions.
        history["items"]["x-go-type"] = "json.RawMessage"
    source = work / "openapi.json"
    source.write_text(json.dumps(document))
    output = work / "output"
    output.mkdir()
    run(
        "go",
        "run",
        "github.com/oapi-codegen/oapi-codegen/v2/cmd/oapi-codegen@v2.8.0",
        "--config",
        str(CONFIG / "config.yaml"),
        "-o",
        str(output / "client.gen.go"),
        str(source),
    )
    text = (output / "client.gen.go").read_text()
    secrets = "// Code generated by codegen/generate.py; DO NOT EDIT.\npackage generated\n\n"
    for name, schema in document["components"]["schemas"].items():
        if any(prop.get("writeOnly") for prop in schema.get("properties", {}).values()):
            assert f"type {name} struct" in text, f"Update the Go diagnostic adapter for {name}"
            secrets += f'func ({name}) String() string {{ return "{name} {{ .. }}" }}\n'
            secrets += f'func ({name}) GoString() string {{ return "{name} {{ .. }}" }}\n'
    (output / "secrets.gen.go").write_text(secrets)
    run("gofmt", "-w", str(output / "secrets.gen.go"))
    return output


def install(output: Path, target: Path) -> None:
    # Only generator-owned directories are replaced, including removed schemas.
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(output, target)


def main() -> None:
    document = json.loads((ROOT / "contract/openapi.json").read_text())
    with tempfile.TemporaryDirectory(prefix="a13n-codegen-") as temp:
        install(generate(document, Path(temp)), TARGET)


if __name__ == "__main__":
    main()
